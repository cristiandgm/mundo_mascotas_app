function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

export function searchColombianLocations(
  query: string,
  filterType: 'all' | 'principal' | 'municipio' = 'all'
): ColombianLocation[] {
  const normQuery = normalizeText(query.trim());

  let list = COLOMBIAN_LOCATIONS;
  if (filterType !== 'all') {
    list = list.filter((loc) => loc.type === filterType);
  }

  if (!normQuery) {
    return list;
  }

  return list.filter((loc) => {
    const nameMatch = normalizeText(loc.name).includes(normQuery);
    const deptMatch = normalizeText(loc.department).includes(normQuery);
    const regionMatch = normalizeText(loc.region).includes(normQuery);
    const keywordMatch = loc.keywords?.some((kw) =>
      normalizeText(kw).includes(normQuery)
    );
    return nameMatch || deptMatch || regionMatch || keywordMatch;
  });
}

function getDistanceFromLatLonInKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371; // Radio de la Tierra en km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/**
 * Determina con alta precisión la ciudad o municipio de Colombia más cercano
 * a partir de coordenadas GPS o texto devuelto por geocodificación inversa.
 */
export function findClosestColombianLocation(
  lat: number,
  lng: number,
  placeName?: string
): ColombianLocation {
  if (placeName && placeName.trim().length > 1) {
    const matches = searchColombianLocations(placeName);
    if (matches.length > 0) {
      return matches[0];
    }
  }

  let closestLoc: ColombianLocation = COLOMBIAN_LOCATIONS[0];
  let minDistance = Infinity;

  for (const loc of COLOMBIAN_LOCATIONS) {
    if (loc.latitude !== undefined && loc.longitude !== undefined) {
      const dist = getDistanceFromLatLonInKm(
        lat,
        lng,
        loc.latitude,
        loc.longitude
      );
      if (dist < minDistance) {
        minDistance = dist;
        closestLoc = loc;
      }
    }
  }

  return closestLoc;
}
